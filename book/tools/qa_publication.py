#!/usr/bin/env python3
"""Keep production/chat commentary out of reader-facing book editions.

This is a content-boundary check, not rights clearance or release certification.
Reports and separate teacher/student support packs are deliberately outside scope.
"""
import json
import re
import zipfile
from pathlib import Path
from lxml import etree
from docx import Document
import pymupdf

ROOT = Path(__file__).resolve().parents[2]
PATTERNS = [
    r'editorial revision', r'classroom guidance added', r'October 2026 editorial',
    r'current edition does not supply', r'verified media links',
    r'separate Class Companion', r'Teacher Implementation Pack', r'Student Practice Pack',
    r'AI-assisted revision', r'as we discussed', r'as discussed in (?:our|this) (?:chat|conversation)',
    r'front.cover concept', r'publication.readiness report', r'original manuscript is unchanged',
    r'generated by python.docx', r'right.click and choose', r'refresh page numbers',
    r'Now students already have the language they need', r'Then have students say',
]


def normalized(value):
    return re.sub(r'\s+', ' ', value)


def main():
    texts = {}
    tree = etree.parse(str(ROOT / 'book/master/master.xhtml'))
    ns = {'x': 'http://www.w3.org/1999/xhtml'}
    texts['semantic book'] = ' '.join(tree.xpath('//x:body//text()', namespaces=ns))
    word = Document(ROOT / 'Master-Speaking-7x10.docx')
    texts['Word'] = '\n'.join([p.text for p in word.paragraphs] +
                              [cell.text for table in word.tables for row in table.rows for cell in row.cells])
    assert word.core_properties.title == 'Master Speaking'
    assert not word.core_properties.comments.strip(), 'Default generator comment leaked into Word metadata'
    assert not word.core_properties.last_modified_by.strip()
    toc = next(p for p in word.paragraphs if 'TOC ' in ''.join(p._p.itertext()))
    assert 'Unit 1 · The Power of Communication' in toc.text
    assert 'Unit 8 · Lingua Franca' in toc.text
    assert toc.text.count('Chapter ') == 32, 'Word contents cache must contain actual chapter labels'
    with zipfile.ZipFile(ROOT / 'Master-Speaking-7x10.docx') as archive:
        xml = etree.fromstring(archive.read('word/document.xml'))
        w = {'w': 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'}
        assert not xml.xpath('//w:ins|//w:del|//w:commentReference', namespaces=w), 'Review markup in publication'
    with zipfile.ZipFile(ROOT / 'Master-Speaking.epub') as archive:
        texts['EPUB'] = '\n'.join(' '.join(etree.fromstring(archive.read(name)).itertext())
                                  for name in archive.namelist() if name.endswith('.xhtml'))
    for name in ['Master-Speaking-print-7x10.pdf', 'Master-Speaking.pdf', 'Master-Speaking-Reading-Edition.pdf']:
        with pymupdf.open(ROOT / name) as pdf:
            texts[name] = '\n'.join(page.get_text() for page in pdf)
            texts[name + ' metadata'] = ' '.join(str(value or '') for value in pdf.metadata.values())
            if name != 'Master-Speaking-print-7x10.pdf':
                assert pdf.metadata['title'] == 'Master Speaking'
    findings = []
    for label, text in texts.items():
        for pattern in PATTERNS:
            if re.search(pattern, normalized(text), re.I):
                findings.append({'edition': label, 'pattern': pattern})
    report = {'ok': not findings, 'scanned': list(texts), 'patterns': len(PATTERNS),
              'findings': findings, 'scope': 'Reader-facing book only; production reports remain separate.'}
    (ROOT / 'book/artifacts/qa_publication.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))
    raise SystemExit(1 if findings else 0)


if __name__ == '__main__':
    main()
